#!/bin/sh
# Xcode Cloud: runs after the clone, before the build.
#
# Configuration.xcconfig is the project's base configuration for every target,
# and it is gitignored because it holds API keys (CLAUDE.md, hard rule 2). A
# fresh clone does not have it, so without this step the build stops with
# "Unable to open base configuration reference file".
#
# The keys come from Xcode Cloud environment variables when they are set
# (Workflow → Environment → add ANTHROPIC_API_KEY etc. as SECRET), otherwise
# they are left empty. The iOS app does not need them: the Assistant that uses
# them is Mac only.
set -e

CONFIG="$CI_PRIMARY_REPOSITORY_PATH/Configuration.xcconfig"

if [ -f "$CONFIG" ]; then
    echo "Configuration.xcconfig already present"
    exit 0
fi

cat > "$CONFIG" <<CONF
// Generated by ci_scripts/ci_post_clone.sh for Xcode Cloud. Not committed.
ANTHROPIC_API_KEY = ${ANTHROPIC_API_KEY:-}
GEMINI_API_KEY = ${GEMINI_API_KEY:-}
GROQ_API_KEY = ${GROQ_API_KEY:-}
CONF

echo "Wrote Configuration.xcconfig for Xcode Cloud"
