@MainActor
struct StudentReportImageGenerator {
    static func generateImage(student: Student, player: Player?, contract: Contract?,
                              programName: String?, coachName: String, orgName: String,
                              trainingStats: TrainingSessionStats?,
                              programContext: ProgramStatsContext? = nil,
                              profileImage: UIImage?,
                              isLightMode: Bool = false) -> UIImage? {
        let view = StudentParentReportView(student: student, player: player, contract: contract,
                                           programName: programName, coachName: coachName,
                                           orgName: orgName, trainingStats: trainingStats,
                                           programContext: programContext,
                                           profileImage: profileImage,
                                           isLightMode: isLightMode)
        let controller = UIHostingController(rootView: view)
        controller.view.backgroundColor = .clear
        
        // Measure the natural content size
        let targetWidth: CGFloat = 380
        let fittingSize = controller.view.systemLayoutSizeFitting(
            CGSize(width: targetWidth, height: UIView.layoutFittingCompressedSize.height),
            withHorizontalFittingPriority: .required,
            verticalFittingPriority: .fittingSizeLevel
        )
        let size = CGSize(width: targetWidth, height: max(fittingSize.height, 700))
        controller.view.bounds = CGRect(origin: .zero, size: size)
        controller.view.layoutIfNeeded()
        
        let renderer = UIGraphicsImageRenderer(size: size)
        return renderer.image { _ in
            controller.view.drawHierarchy(in: controller.view.bounds, afterScreenUpdates: true)
        }
    }
}
