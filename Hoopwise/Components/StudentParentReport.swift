    private func loadProfileImage() {
        #if os(iOS)
        // Try to load from player's profileImageData first
        if let data = player?.profileImageData, let img = UIImage(data: data) {
            profileImage = img
            return
        }
        
        // Try to load from cache using student ID
        let cacheId = ImageCacheManager.studentImageId(student.id)
        if let cached = ImageCacheManager.shared.image(for: cacheId) {
            profileImage = cached
            return
        }
        
        // Try to load from URL
        if let urlString = student.profileImageUrl, !urlString.isEmpty {
            Task {
                let loaded = await ImageCacheManager.shared.loadImage(for: cacheId, from: urlString)
                await MainActor.run {
                    profileImage = loaded
                }
            }
        }
        #else
        // macOS: Try to load from player's profileImageData first
        if let data = player?.profileImageData, let img = NSImage(data: data) {
            profileImage = img
            return
        }
        #endif
    }
    
    private func shareReport() {
        #if os(iOS)
        isGenerating = true
        
        Task {
            if let image = await StudentReportImageGenerator.generateImage(
                student: student,
                player: player,
                contract: contract,
                programName: programName,
                coachName: coachName,
                orgName: orgName,
                trainingStats: trainingStats,
                programContext: programContext,
                profileImage: profileImage,
                isLightMode: isLightMode
            ) {
                generatedImage = image
                showShareSheet = true
            }
            isGenerating = false
        }
        #endif
    }
}

