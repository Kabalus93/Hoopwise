                Spacer()
                
                Image(systemName: "chevron.right")
                    .font(.system(size: 11, weight: .semibold))
                    .foregroundColor(AppTheme.textTertiary)
            }
            .padding(12)
            .background(AppTheme.cardBackground)
            .cornerRadius(12)
        }
    }
    
    // MARK: - Weekly Schedule Card (for phase-less programs)
    private var weeklyScheduleCard: some View {
        VStack(alignment: .leading, spacing: 10) {
            HStack {
                Text(isChinese ? "训练日" : "TRAINING DAYS")
                    .font(.system(size: 10, weight: .bold, design: .monospaced))
                    .foregroundColor(AppTheme.textTertiary)
                Spacer()
                if weeklySchedule.count > 0 {
                    Text("\(weeklySchedule.count)")
                        .font(.system(size: 11, weight: .bold, design: .monospaced))
                        .foregroundColor(accentColor)
                        .padding(.horizontal, 8)
                        .padding(.vertical, 3)
                        .background(accentColor.opacity(0.15))
                        .cornerRadius(6)
                }
            }
            
            // Compact day grid - 2 rows
            VStack(spacing: 6) {
                HStack(spacing: 6) {
                    ForEach(Weekday.allCases.prefix(4), id: \.self) { day in
                        compactDayChip(day)
                    }
                }
                HStack(spacing: 6) {
                    ForEach(Weekday.allCases.suffix(3), id: \.self) { day in
                        compactDayChip(day)
                    }
                    Spacer()
                }
            }
            
            // Show focus pickers for selected days
            if !weeklySchedule.isEmpty {
                VStack(spacing: 6) {
                    ForEach(weeklySchedule.sorted { $0.weekday.rawValue < $1.weekday.rawValue }, id: \.weekday) { session in
                        compactFocusRow(for: session.weekday)
                    }
                }
            }
        }
        .padding(12)
        .background(AppTheme.cardBackground)
        .cornerRadius(12)
    }
    
    private func compactDayChip(_ day: Weekday) -> some View {
        let isSelected = weeklySchedule.contains { $0.weekday == day }
        
        return Button(action: {
            withAnimation(.easeInOut(duration: 0.15)) {
                if isSelected {
                    weeklySchedule.removeAll { $0.weekday == day }
                } else {
                    weeklySchedule.append(WeekdaySession(weekday: day, focus: []))
                }
            }
        }) {
            Text(day.shortName)
                .font(.system(size: 12, weight: .semibold))
                .foregroundColor(isSelected ? .white : AppTheme.textSecondary)
                .frame(maxWidth: .infinity)
                .padding(.vertical, 10)
                .background(isSelected ? accentColor : AppTheme.surfaceColor)
                .cornerRadius(8)
        }
    }
    
    private func compactFocusRow(for day: Weekday) -> some View {
        let binding = Binding<[TrainingFocus]>(
            get: { weeklySchedule.first { $0.weekday == day }?.focus ?? [] },
            set: { newValue in
                if let index = weeklySchedule.firstIndex(where: { $0.weekday == day }) {
                    weeklySchedule[index].focus = newValue
                }
            }
        )
        
        return HStack(spacing: 8) {
            Text(day.shortName)
                .font(.system(size: 10, weight: .bold, design: .monospaced))
                .foregroundColor(accentColor)
                .frame(width: 32)
            
            ScrollView(.horizontal, showsIndicators: false) {
                HStack(spacing: 4) {
                    ForEach(TrainingFocus.allCases, id: \.self) { focus in
                        let isSelected = binding.wrappedValue.contains(focus)
                        Button(action: {
                            withAnimation(.easeInOut(duration: 0.1)) {
                                if isSelected {
                                    binding.wrappedValue.removeAll { $0 == focus }
                                } else {
                                    binding.wrappedValue.append(focus)
                                }
                            }
                        }) {
                            Text(focus.displayName)
                                .font(.system(size: 10, weight: .medium))
                                .foregroundColor(isSelected ? .white : AppTheme.textTertiary)
                                .padding(.horizontal, 8)
                                .padding(.vertical, 4)
                                .background(isSelected ? accentColor.opacity(0.8) : AppTheme.surfaceColor)
                                .cornerRadius(10)
                        }
                    }
                }
            }
        }
        .padding(.vertical, 6)
        .padding(.horizontal, 8)
        .background(accentColor.opacity(0.06))
        .cornerRadius(8)
    }
    
    // MARK: - Chip Views
    private func ageChip(_ group: AgeGroup) -> some View {
        let isSelected = selectedAgeGroup == group
        let groupColor = Color(hex: group.colorHex)
        
        return Button(action: {
            withAnimation(.easeInOut(duration: 0.15)) {
                selectedAgeGroup = group
            }
        }) {
            Text(group.rawValue)
                .font(.system(size: 12, weight: .bold, design: .monospaced))
                .foregroundColor(isSelected ? .white : groupColor)
                .padding(.horizontal, 10)
                .padding(.vertical, 6)
                .background(isSelected ? groupColor : groupColor.opacity(0.12))
                .cornerRadius(12)
        }
    }
    
    private func locationChip(_ location: Location) -> some View {
        let isSelected = selectedLocationId == location.id
        
        return Button(action: {
            withAnimation(.easeInOut(duration: 0.15)) {
                selectedLocationId = location.id
            }
        }) {
            HStack(spacing: 4) {
                Image(systemName: "mappin")
                    .font(.system(size: 9))
                Text(location.name)
                    .font(.system(size: 12, weight: .medium))
            }
            .foregroundColor(isSelected ? .white : AppTheme.textSecondary)
            .padding(.horizontal, 10)
            .padding(.vertical, 6)
            .background(isSelected ? accentColor : AppTheme.surfaceColor)
            .cornerRadius(12)
        }
    }
    
    private func coachChip(_ id: UUID?, name: String, initials: String = "—", color: Color = .gray) -> some View {
        let isSelected = selectedCoachId == id
        
        return Button(action: {
            withAnimation(.easeInOut(duration: 0.15)) {
                selectedCoachId = id
            }
        }) {
            HStack(spacing: 4) {
                Circle()
                    .fill(color.opacity(isSelected ? 1 : 0.5))
                    .frame(width: 18, height: 18)
                    .overlay(
                        Text(initials.prefix(2))
                            .font(.system(size: 8, weight: .bold))
                            .foregroundColor(.white)
                    )
                Text(name.split(separator: " ").first.map(String.init) ?? name)
                    .font(.system(size: 12, weight: .medium))
            }
            .foregroundColor(isSelected ? .white : AppTheme.textSecondary)
            .padding(.horizontal, 8)
            .padding(.vertical, 5)
            .background(isSelected ? accentColor : AppTheme.surfaceColor)
            .cornerRadius(12)
        }
    }
    
    // MARK: - Helpers
    private func sectionHeader(_ title: String, icon: String) -> some View {
        HStack(spacing: 6) {
            Image(systemName: icon)
                .font(.system(size: 11))
                .foregroundColor(AppTheme.textTertiary)
            Text(title)
                .font(.system(size: 11, weight: .bold, design: .monospaced))
                .foregroundColor(AppTheme.textSecondary)
        }
    }
    
    // MARK: - Create Program
    private func createProgram() {
        let endDate = Calendar.current.date(byAdding: .weekOfYear, value: durationWeeks, to: startDate)
        let locationName = selectedLocationId != nil ? dataManager.locations.first(where: { $0.id == selectedLocationId })?.name : nil
        
        let program = Program(
            name: autoGeneratedName,
            programType: .group,
            ageGroup: selectedAgeGroup,
            durationWeeks: durationWeeks,
            enrolledStudentIds: Array(selectedStudentIds),
            coachId: selectedCoachId,
            createdByCoachId: dataManager.loggedInCoachId,
            status: .active,
            mascot: selectedMascot,
            startDate: startDate,
            endDate: endDate,
            recurringDays: weeklySchedule.map { $0.weekday },
            defaultSessionTime: sessionTime,
            defaultSessionDurationMinutes: sessionDuration,
            locationId: selectedLocationId,
            locationName: locationName,
            usesPhases: usesPhases
        )
        
        dataManager.addProgram(program)
        
        // If not using phases, create recurring sessions
        if !usesPhases {
            createRecurringSessions(for: program)
        }
        
        dismiss()
    }
    
    private func createRecurringSessions(for program: Program) {
        let calendar = Calendar.current
        var currentDate = startDate
        let endDate = calendar.date(byAdding: .weekOfYear, value: durationWeeks, to: startDate) ?? startDate
        
        // Get time components from sessionTime
        let timeComponents = calendar.dateComponents([.hour, .minute], from: sessionTime)
        
        while currentDate <= endDate {
            let weekday = calendar.component(.weekday, from: currentDate)
            
            // Check if this day is in our schedule
            if let session = weeklySchedule.first(where: { $0.weekday.rawValue == weekday }) {
                // Create session for this day
                let sessionStartTime = calendar.date(bySettingHour: timeComponents.hour ?? 18,
                                                      minute: timeComponents.minute ?? 0,
                                                      second: 0, of: currentDate) ?? currentDate
                let sessionEndTime = calendar.date(byAdding: .minute, value: sessionDuration, to: sessionStartTime) ?? sessionStartTime
                
                // Generate title from focus
                let focusTitle = session.focus.isEmpty 
                    ? (isChinese ? "训练" : "Training")
                    : session.focus.map { $0.displayName }.joined(separator: " & ")
                
                let sessionEvent = SessionEvent(
                    programId: program.id,
                    sessionType: .training,
                    title: focusTitle,
                    date: currentDate,
                    startTime: sessionStartTime,
                    endTime: sessionEndTime,
                    location: program.locationName,
                    developmentFocus: session.focus,
                    createdByCoachId: dataManager.loggedInCoachId
                )
                
                dataManager.addSessionEvent(sessionEvent)
            }
            
            // Move to next day
            currentDate = calendar.date(byAdding: .day, value: 1, to: currentDate) ?? currentDate
        }
    }
}

// MARK: - Weekday Session Model
struct WeekdaySession: Identifiable {
    let id = UUID()
    var weekday: Weekday
    var focus: [TrainingFocus]
}

