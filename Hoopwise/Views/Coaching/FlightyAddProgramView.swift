    private func sectionHeader(title: String, icon: String) -> some View {
        HStack(spacing: 6) {
            Image(systemName: icon)
                .font(.system(size: 11))
                .foregroundColor(.white.opacity(0.4))
            Text(title)
                .font(.system(size: 12, weight: .bold, design: .monospaced))
                .foregroundColor(.white.opacity(0.6))
        }
    }
    
    private func addObjective() {
        guard !newObjective.isEmpty else { return }
        objectives.append(newObjective)
        newObjective = ""
    }
    
    private func saveProgram() {
        let weeks = Int(durationWeeks) ?? 12
        let endDate = Calendar.current.date(byAdding: .weekOfYear, value: weeks, to: startDate)
        
        // Get location name
        let locationName = selectedLocationId != nil ? dataManager.locations.first(where: { $0.id == selectedLocationId })?.name : nil
        
        let program = Program(
            name: autoGeneratedName,
            programType: selectedProgramType,
            ageGroup: selectedAgeGroup,
            durationWeeks: weeks,
            description: description.isEmpty ? nil : description,
            objectives: objectives,
            enrolledStudentIds: Array(selectedStudentIds),
            coachId: selectedCoachId,
            createdByCoachId: selectedCoachId ?? dataManager.loggedInCoachId ?? AuthManager.shared.currentUser?.id,
            status: .active,
            mascot: selectedMascot,
            startDate: startDate,
            endDate: endDate,
            stars: .one,
            recurringDays: Array(selectedDays),
            defaultSessionTime: sessionTime,
            defaultSessionDurationMinutes: sessionDuration,
            locationId: selectedLocationId,
            locationName: locationName
        )
        
        dataManager.addProgram(program)
        dismiss()
    }
