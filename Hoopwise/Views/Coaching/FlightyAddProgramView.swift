    // MARK: - Age Category Section
    private var ageCategorySection: some View {
        VStack(alignment: .leading, spacing: 16) {
            sectionHeader(title: "AGE CATEGORY", icon: "person.2.fill")
            
            // Category chips
            ScrollView(.horizontal, showsIndicators: false) {
                HStack(spacing: 10) {
                    ForEach(AgeGroup.allCases, id: \.self) { group in
                        flightyCategoryChip(group)
                    }
                }
            }
            
            // Category info card
            categoryInfoCard
        }
        .padding(20)
        .background(Color(hex: "#1a1a2e"))
        .cornerRadius(16)
    }
    
    private func flightyCategoryChip(_ group: AgeGroup) -> some View {
        let isSelected = selectedAgeGroup == group
        let groupColor = Color(hex: group.colorHex)
        
        return Button(action: {
            withAnimation(.easeInOut(duration: 0.2)) {
                selectedAgeGroup = group
            }
        }) {
            VStack(spacing: 4) {
                Text(group.rawValue)
                    .font(.system(size: 14, weight: .bold, design: .monospaced))
                Text(group.categoryName)
                    .font(.system(size: 9, weight: .medium))
                    .lineLimit(1)
            }
            .foregroundColor(isSelected ? .black : groupColor)
            .padding(.horizontal, 16)
            .padding(.vertical, 12)
            .background(isSelected ? groupColor : groupColor.opacity(0.15))
            .cornerRadius(12)
            .overlay(
                RoundedRectangle(cornerRadius: 12)
                    .stroke(isSelected ? groupColor : Color.clear, lineWidth: 2)
            )
        }
    }
    
