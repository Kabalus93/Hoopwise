        VStack(alignment: .leading, spacing: 12) {
            sectionHeader(title: "DIFFICULTY LEVEL", icon: "chart.bar.fill")
            
            Text("Set the skill level for enrolled athletes (1 = Beginner, 10 = Elite)")
                .font(.system(size: 12))
