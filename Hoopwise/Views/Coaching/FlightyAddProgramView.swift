import SwiftUI
import PhotosUI

// MARK: - Flighty-Styled Add Program View
/// A redesigned program creation form with Flighty's dark, confident aesthetic
struct FlightyAddProgramView: View {
    @EnvironmentObject var dataManager: DataManager
    @Environment(\.dismiss) var dismiss
    
    // Basic Info
    @State private var selectedProgramType: ProgramType = .group
    @State private var selectedAgeGroup: AgeGroup = .u12
    @State private var selectedMascot: ProgramMascot = .eagle
    @State private var durationWeeks = "12"
    @State private var description = ""
    @State private var difficultyLevel: Double = 5.0  // 1-10 scale
    
    // Coach Assignment
    @State private var selectedCoachId: UUID? = nil
    
    // Location
    @State private var selectedLocationId: UUID? = nil
    
    // Recurring schedule
    @State private var selectedDays: Set<Weekday> = [.monday]
    @State private var sessionTime = Calendar.current.date(bySettingHour: 18, minute: 0, second: 0, of: Date()) ?? Date()
    @State private var sessionDuration = 90
    
    // Objectives
    @State private var objectives: [String] = []
    @State private var newObjective = ""
    
    // Enrollment
    @State private var selectedStudentIds: Set<UUID> = []
    @State private var showingStudentPicker = false
    @State private var showingMascotPicker = false
    
    // Dates
    @State private var hasStartDate = false
    @State private var startDate = Date()
    
    // Stars/Tier Rating
    @State private var selectedStars: ProgramStars = .one
    
    var isValid: Bool {
        !selectedDays.isEmpty && selectedLocationId != nil
    }
    
    var autoGeneratedName: String {
        var parts: [String] = []
        
        // Day of the week (first selected day)
        if let firstDay = selectedDays.sorted(by: { $0.rawValue < $1.rawValue }).first {
            parts.append(firstDay.displayName)
        }
        
        // Time
        let formatter = DateFormatter()
        formatter.dateFormat = "h:mma"
        parts.append(formatter.string(from: sessionTime))
        
        // Location
        if let locationId = selectedLocationId,
           let location = dataManager.locations.first(where: { $0.id == locationId }) {
            parts.append(location.name)
        }
        
        return parts.joined(separator: " ")
    }
    
    var accentColor: Color {
        selectedMascot.color
    }
    
    var body: some View {
        NavigationStack {
            ScrollView(showsIndicators: false) {
                VStack(spacing: 0) {
                    // Hero header with mascot
                    heroHeader
                    
                    // Content sections
                    VStack(spacing: 20) {
                        // Auto-generated name preview
                        namePreviewSection
                        
                        // Program type selection
                        programTypeSection
                        
                        // Mascot selection
                        mascotSection
                        
                        // Age category
                        ageCategorySection
                        
                        // Duration
                        durationSection
                        
                        // Start date
                        startDateSection
                        
                        // Coach assignment
                        coachSection
                        
                        // Location
                        locationSection
                        
                        // Recurring days
                        recurringDaysSection
                        
                        // Session time
                        sessionTimeSection
                        
                        // Student enrollment
                        enrollmentSection
                        
                        // Objectives
                        objectivesSection
                        
                        // Description
                        descriptionSection
                        
                        // Difficulty level
                        difficultyLevelSection
                        
                        Spacer(minLength: 100)
                    }
                    .padding(20)
                }
            }
            .background(Color.black.ignoresSafeArea())
            .navigationBarTitleDisplayModeCompat(.inline)
            .toolbar {
                ToolbarItem(placement: .cancellationAction) {
                    Button("Cancel") { dismiss() }
                        .foregroundColor(.white.opacity(0.7))
                }
                ToolbarItem(placement: .confirmationAction) {
                    Button(action: saveProgram) {
                        Text("CREATE")
                            .font(.system(size: 14, weight: .bold, design: .monospaced))
                            .foregroundColor(isValid ? .black : .white.opacity(0.3))
                            .padding(.horizontal, 16)
                            .padding(.vertical, 8)
                            .background(isValid ? accentColor : Color.white.opacity(0.1))
                            .cornerRadius(8)
                    }
                    .disabled(!isValid)
                }
            }
            .sheet(isPresented: $showingStudentPicker) {
                StudentPickerView(selectedIds: $selectedStudentIds, ageGroup: selectedAgeGroup)
            }
            .sheet(isPresented: $showingMascotPicker) {
                FlightyMascotSelectionView(selectedMascot: $selectedMascot)
            }
            .onChange(of: selectedAgeGroup) { _, newValue in
                objectives = newValue.defaultObjectives
                description = newValue.focusDescription
            }
            .onAppear {
                objectives = selectedAgeGroup.defaultObjectives
                description = selectedAgeGroup.focusDescription
            }
        }
    }
    
    // MARK: - Hero Header
    private var heroHeader: some View {
        VStack(spacing: 16) {
            // Mascot preview
            ZStack {
                Circle()
                    .fill(
                        LinearGradient(
                            colors: [accentColor, accentColor.opacity(0.6)],
                            startPoint: .topLeading,
                            endPoint: .bottomTrailing
                        )
                    )
                    .frame(width: 100, height: 100)
                
                Image(systemName: selectedMascot.icon)
                    .font(.system(size: 44, weight: .bold))
                    .foregroundColor(.white)
            }
            .shadow(color: accentColor.opacity(0.4), radius: 16, x: 0, y: 8)
            
            Text("NEW PROGRAM")
                .font(.system(size: 20, weight: .bold, design: .monospaced))
                .foregroundColor(.white)
            
            if !autoGeneratedName.isEmpty {
                Text(autoGeneratedName)
                    .font(.system(size: 16, weight: .semibold))
                    .foregroundColor(accentColor)
            } else {
                Text(selectedMascot.displayName)
                    .font(.system(size: 16, weight: .semibold))
                    .foregroundColor(accentColor)
            }
        }
        .frame(maxWidth: .infinity)
        .padding(.vertical, 32)
    }
    
    // MARK: - Name Preview Section
    private var namePreviewSection: some View {
        VStack(alignment: .leading, spacing: 12) {
            sectionHeader(title: "PROGRAM NAME (AUTO-GENERATED)", icon: "text.badge.checkmark")
            
            HStack {
                Image(systemName: "sparkles")
                    .font(.system(size: 16))
                    .foregroundColor(accentColor)
                
                Text(autoGeneratedName.isEmpty ? "Select day, time & location" : autoGeneratedName)
                    .font(.system(size: 18, weight: .bold))
                    .foregroundColor(autoGeneratedName.isEmpty ? .white.opacity(0.3) : .white)
                
                Spacer()
            }
            .padding(16)
            .background(Color.white.opacity(0.05))
            .cornerRadius(12)
            .overlay(
                RoundedRectangle(cornerRadius: 12)
                    .stroke(autoGeneratedName.isEmpty ? Color.white.opacity(0.1) : accentColor.opacity(0.5), lineWidth: 1)
            )
            
            Text("Name is automatically created from: Day + Time + Location")
                .font(.system(size: 11))
                .foregroundColor(.white.opacity(0.4))
        }
        .padding(20)
        .background(Color(hex: "#1a1a2e"))
        .cornerRadius(16)
    }
    
    // MARK: - Program Type Section
    private var programTypeSection: some View {
        VStack(alignment: .leading, spacing: 16) {
            sectionHeader(title: "PROGRAM TYPE", icon: "rectangle.3.group.fill")
            
            VStack(spacing: 10) {
                ForEach(ProgramType.allCases, id: \.self) { type in
                    Button(action: { selectedProgramType = type }) {
                        HStack(spacing: 12) {
                            Image(systemName: type.icon)
                                .font(.system(size: 18))
                                .foregroundColor(selectedProgramType == type ? accentColor : .white.opacity(0.5))
                                .frame(width: 32)
                            
                            VStack(alignment: .leading, spacing: 2) {
                                Text(type.displayName)
                                    .font(.system(size: 14, weight: .semibold))
                                    .foregroundColor(selectedProgramType == type ? .white : .white.opacity(0.7))
                                
                                Text(type.description)
                                    .font(.system(size: 11))
                                    .foregroundColor(.white.opacity(0.4))
                            }
                            
                            Spacer()
                            
                            if selectedProgramType == type {
                                Image(systemName: "checkmark.circle.fill")
                                    .font(.system(size: 20))
                                    .foregroundColor(accentColor)
                            }
                        }
                        .padding(14)
                        .background(selectedProgramType == type ? accentColor.opacity(0.1) : Color.white.opacity(0.03))
                        .cornerRadius(12)
                        .overlay(
                            RoundedRectangle(cornerRadius: 12)
                                .stroke(selectedProgramType == type ? accentColor : Color.white.opacity(0.1), lineWidth: selectedProgramType == type ? 2 : 1)
                        )
                    }
                }
            }
        }
        .padding(20)
        .background(Color(hex: "#1a1a2e"))
        .cornerRadius(16)
    }
    
    // MARK: - Mascot Section
    private var mascotSection: some View {
        VStack(alignment: .leading, spacing: 16) {
            sectionHeader(title: "TEAM IDENTITY", icon: "star.fill")
            
            Button(action: { showingMascotPicker = true }) {
