    private func coachButton(_ id: UUID?, name: String, initials: String, color: Color, isYou: Bool = false) -> some View {
        let isSelected = selectedCoachId == id
        return Button(action: {
            withAnimation(.easeInOut(duration: 0.2)) {
                selectedCoachId = id
            }
        }) {
            VStack(spacing: 8) {
                ZStack {
                    Circle()
                        .fill(isSelected ? color : color.opacity(0.3))
                        .frame(width: 50, height: 50)
                    Text(initials)
                        .font(.system(size: 14, weight: .bold))
                        .foregroundColor(.white)
                }
                .overlay(
                    Circle()
                        .stroke(isSelected ? accentColor : Color.clear, lineWidth: 3)
                )
                
                VStack(spacing: 2) {
                    Text(name.split(separator: " ").first.map(String.init) ?? name)
                        .font(.system(size: 11, weight: .medium))
                        .foregroundColor(isSelected ? .white : .white.opacity(0.6))
                        .lineLimit(1)
                    
                    if isYou {
                        Text("YOU")
                            .font(.system(size: 8, weight: .bold, design: .monospaced))
                            .foregroundColor(accentColor)
                    }
                }
            }
            .frame(width: 70)
        }
    }
    
    // MARK: - Objectives Section
