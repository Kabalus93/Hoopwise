    // MARK: - Recurring Days Section
    private var recurringDaysSection: some View {
        VStack(alignment: .leading, spacing: 12) {
            sectionHeader(title: "RECURRING DAYS", icon: "calendar.badge.clock")
            
            Text("Select which days sessions will occur")
                .font(.system(size: 12))
                .foregroundColor(.white.opacity(0.5))
            
            LazyVGrid(columns: [GridItem(.flexible()), GridItem(.flexible()), GridItem(.flexible())], spacing: 10) {
                ForEach(Weekday.allCases, id: \.self) { day in
                    dayButton(day)
                }
            }
        }
        .padding(20)
        .background(Color(hex: "#1a1a2e"))
        .cornerRadius(16)
    }
    
    private func dayButton(_ day: Weekday) -> some View {
        let isSelected = selectedDays.contains(day)
        return Button(action: {
            withAnimation(.easeInOut(duration: 0.2)) {
                if isSelected {
                    selectedDays.remove(day)
                } else {
                    selectedDays.insert(day)
                }
            }
        }) {
            VStack(spacing: 4) {
                Text(day.shortName)
                    .font(.system(size: 12, weight: .bold))
                    .foregroundColor(isSelected ? .black : .white.opacity(0.6))
            }
            .frame(maxWidth: .infinity)
            .padding(.vertical, 12)
            .background(isSelected ? accentColor : Color.white.opacity(0.05))
            .cornerRadius(10)
            .overlay(
                RoundedRectangle(cornerRadius: 10)
                    .stroke(isSelected ? accentColor : Color.white.opacity(0.1), lineWidth: isSelected ? 2 : 1)
            )
        }
    }
    
